#!/usr/bin/env python3
"""gen-compose.py — writes std/unicode/compose.cst: canonical composition of pairs.

    python3 tools/gen-compose.py [UCD_DIR]      (from the repository root)

UCD_DIR holds UnicodeData.txt and DerivedNormalizationProps.txt — by default
../caustic-unicode/tools/ucd, the same files std/unicode/tables were generated
from, so the composition data and the property data are one Unicode version.

The table is every primary composite: a code point whose canonical
decomposition is exactly two code points and which is not
Full_Composition_Exclusion. That is the pair step of NFC — "e" + U+0301 is
"é" — which is what a terminal needs to fold a combining mark into the
character before it, and what a keyboard's dead keys need to turn an accent
and a letter into one character.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ucd = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(ROOT), "caustic-unicode", "tools", "ucd")
    try:
        with open(os.path.join(ucd, "DerivedNormalizationProps.txt")) as fh:
            dnp = fh.read()
        with open(os.path.join(ucd, "UnicodeData.txt")) as fh:
            udata = fh.read()
    except OSError as e:
        sys.exit("gen-compose: {} — pass the UCD directory".format(e))

    m = re.search(r"DerivedNormalizationProps-([0-9.]+)\.txt", dnp)
    version = m.group(1) if m else "?"

    excluded = set()
    for line in dnp.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        if len(fields) < 2 or fields[1] != "Full_Composition_Exclusion":
            continue
        if ".." in fields[0]:
            a, b = fields[0].split("..")
            excluded.update(range(int(a, 16), int(b, 16) + 1))
        else:
            excluded.add(int(fields[0], 16))

    pairs = []
    for line in udata.splitlines():
        f = line.split(";")
        if len(f) < 6 or not f[5] or f[5].startswith("<"):
            continue
        cp = int(f[0], 16)
        parts = f[5].split()
        if len(parts) != 2 or cp in excluded:
            continue
        pairs.append((int(parts[0], 16), int(parts[1], 16), cp))
    pairs.sort()

    blob = []
    for a, b, c in pairs:
        for v in (a, b, c):
            blob.append("".join("\\x{:02x}".format((v >> s) & 255) for s in (0, 8, 16, 24)))

    out = []
    out.append("// GENERATED by tools/gen-compose.py from the UCD {} (UnicodeData.txt,\n".format(version))
    out.append("// DerivedNormalizationProps.txt). DO NOT EDIT. Regenerate from the repository\n")
    out.append("// root: python3 tools/gen-compose.py [UCD_DIR]\n")
    out.append("//\n")
    out.append("// Canonical composition of a pair — the step of NFC that turns \"e\" + U+0301\n")
    out.append("// into \"é\". Every primary composite: a code point whose canonical\n")
    out.append("// decomposition is exactly two code points and which is not\n")
    out.append("// Full_Composition_Exclusion. 12 bytes an entry — first, second, composite,\n")
    out.append("// each u32 LE — sorted by (first, second).\n\n")
    out.append("let is i64 as N_PAIRS with imut = {};\n\n".format(len(pairs)))
    out.append("let is *u8 as PAIRS with imut = \"{}\";\n\n".format("".join(blob)))
    out.append("""fn _u32(off as i64) as i64 {
    let is *u8 as t = PAIRS;
    return cast(i64, t[off]) | (cast(i64, t[off + 1]) << 8)
         | (cast(i64, t[off + 2]) << 16) | (cast(i64, t[off + 3]) << 24);
}

// The character `first` followed by `second` composes to, or 0 when the pair
// does not compose: compose(0x65, 0x301) is 0xE9, compose(0x65, 0x65) is 0.
fn compose(first as i64, second as i64) as i64 {
    // Hangul syllables compose by arithmetic, not by table (Unicode 3.12): a
    // leading consonant and a vowel make an LV syllable, and an LV syllable and
    // a trailing consonant make an LVT one.
    if (first >= 0x1100 && first < 0x1113 && second >= 0x1161 && second < 0x1176) {
        return 0xAC00 + ((first - 0x1100) * 21 + (second - 0x1161)) * 28;
    }
    if (first >= 0xAC00 && first < 0xD7A4 && (first - 0xAC00) % 28 == 0
        && second > 0x11A7 && second < 0x11C3) {
        return first + (second - 0x11A7);
    }
    let is i64 as lo with mut = 0;
    let is i64 as hi with mut = N_PAIRS - 1;
    while (lo <= hi) {
        let is i64 as mid = (lo + hi) / 2;
        let is i64 as a = _u32(mid * 12);
        let is i64 as b = _u32(mid * 12 + 4);
        if (first < a || (first == a && second < b)) { hi = mid - 1; }
        else if (first > a || (first == a && second > b)) { lo = mid + 1; }
        else { return _u32(mid * 12 + 8); }
    }
    return 0;
}
""")
    path = os.path.join(ROOT, "std", "unicode", "compose.cst")
    with open(path, "w") as fh:
        fh.write("".join(out))
    print("gen-compose: {} pairs (UCD {}) -> std/unicode/compose.cst".format(len(pairs), version))


if __name__ == "__main__":
    main()
